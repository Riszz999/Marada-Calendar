/** ชื่อเดือน + ปี (พ.ศ. สำหรับไทย, ค.ศ. สำหรับอังกฤษ) */
export function monthLabel(lang, year, month) {
  const name = lang === "th" ? THAI_MONTHS[month] : EN_MONTHS[month];
  return `${name} ${lang === "th" ? year + 543 : year}`;
}

export function eraLabel(lang, year) {
  return lang === "th"
    ? `ค.ศ. ${year} · พ.ศ. ${year + 543}`
    : `B.E. ${year + 543}`;
}

/** 'YYYY-MM-DD' -> 'วันจันทร์ที่ 17 สิงหาคม 2569' / 'Monday, August 17, 2026' */
export function longDate(lang, dateKey) {
  const [y, m, d] = dateKey.split("-").map(Number);
  const dt = new Date(y, m - 1, d);
  if (lang === "th") {
    return `วัน${THAI_WD_FULL[dt.getDay()]}ที่ ${d} ${THAI_MONTHS[m - 1]} ${y + 543}`;
  }
  return `${EN_WD_FULL[dt.getDay()]}, ${EN_MONTHS[m - 1]} ${d}, ${y}`;
}
